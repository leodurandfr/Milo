#!/usr/bin/env python3
"""Generate the reference pages under docs/reference/ from the code.

    python tools/docs/generate_reference.py            # rewrite the pages
    python tools/docs/generate_reference.py --check    # exit 1 if one is stale

Run from the repository root, with the backend's virtualenv. Each page is read
from the code it describes: the WebSocket events from `ws_events.py`, the audio
state from `audio_wire.py`, the commands from each source's `COMMANDS`, the REST
surface from the app's OpenAPI schema, the hardware from `hardware/registry.py`.
Of a class docstring, only the first paragraph is published: what follows it is
for the people working on the code. `backend/tests/architecture/test_reference_docs.py`
fails when a committed page no longer matches what this script writes.
"""
import argparse
import enum
import inspect
import json
import sys
import types
import typing
from pathlib import Path

from pydantic import BaseModel

REPO = Path(__file__).resolve().parents[2]
OUT_DIR = REPO / "docs" / "reference"

for path in (REPO, REPO / "tools"):
    if str(path) not in sys.path:
        sys.path.insert(0, str(path))

import api_surface  # noqa: E402

HEADER = (
    "<!-- Generated by tools/docs/generate_reference.py from the code. Do not edit by hand:\n"
    "     change the code, then run the script. A test fails when this file is stale. -->\n"
)

STABILITY_NOTE = (
    "**Contracted** marks what Milo-Mac or Milo-iOS relies on: a change to it is listed under "
    "*API and integration changes* in the release notes. Everything else is **internal** and "
    "may change in any release. See [Integration](../integration.md#stability)."
)


