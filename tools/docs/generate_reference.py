def first_paragraph(obj) -> str:
    """The published part of a docstring: its first paragraph, on one line."""
    doc = inspect.getdoc(obj) or ""
    return " ".join(doc.split("\n\n")[0].split())


def own_doc(cls) -> str:
    """The class's own first paragraph, never one inherited from a base."""
    return first_paragraph(cls) if cls.__dict__.get("__doc__") else ""


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def anchor(name: str) -> str:
    return name.lower()


class TypeNames:
    """Renders annotations as JSON types, collecting the models and enums they name.

    `external` maps a model, an enum or an alias already documented on another
    page to that page's file name, so it is linked rather than described twice.
    `aliases` names the `Literal` types the code names, which would otherwise
    be spelled out at every use.
    """

    def __init__(self, external: dict = None, aliases: dict = None):
        self.external = external or {}
        self.aliases = aliases or {}
        self.models: list = []
        self.enums: dict = {}

    def _link(self, name: str, key) -> str:
        return f"[{name}]({self.external.get(key, '')}#{anchor(name)})"

    def name(self, annotation) -> str:
        origin = typing.get_origin(annotation)
        args = typing.get_args(annotation)
        if origin is typing.Literal:
            for alias, alias_name in self.aliases.items():
                if annotation == alias:
                    if alias_name not in self.external:
                        self.enums.setdefault(alias_name, (alias_name, "", [str(a) for a in args]))
                    return self._link(alias_name, alias_name)
            return " | ".join(json.dumps(a) for a in args)
        if origin is typing.Annotated:
            return self.name(args[0])
        if origin in (typing.Union, types.UnionType):
            parts = [self.name(a) for a in args if a is not type(None)]
            if type(None) in args:
                parts.append("null")
            return " | ".join(parts)
        if origin in (list, tuple, set, frozenset):
            inner = [a for a in args if a is not Ellipsis]
            return f"{self.name(inner[0]) if inner else 'any'}[]"
        if origin is dict:
            return "object"
        if annotation is typing.Any:
            return "any"
        if isinstance(annotation, type):
            if issubclass(annotation, BaseModel):
                if annotation not in self.external and annotation not in self.models:
                    self.models.append(annotation)
                return self._link(annotation.__name__, annotation)
            if issubclass(annotation, enum.Enum):
                if annotation not in self.external:
                    self.enums.setdefault(
                        annotation.__name__,
                        (annotation, own_doc(annotation), [m.value for m in annotation]),
                    )
                return self._link(annotation.__name__, annotation)
            simple = {str: "string", int: "integer", float: "number", bool: "boolean",
                      dict: "object", list: "any[]"}
            if annotation in simple:
                return simple[annotation]
        raise TypeError(f"no JSON name for {annotation!r}")


def field_rows(model, names: TypeNames) -> list:
    """Field and type: a published model is read, so every field is on the wire."""
    rows = ["| Field | Type |", "|---|---|"]
    for field_name, field in model.model_fields.items():
        rows.append(f"| `{field_name}` | {cell(names.name(field.annotation))} |")
    return rows


def model_section(model, names: TypeNames, level: str = "###") -> list:
    lines = [f"{level} {model.__name__}", ""]
    doc = own_doc(model)
    if doc:
        lines += [doc, ""]
    if not model.model_fields:
        return lines + ["No fields.", ""]
    return lines + field_rows(model, names) + [""]


def appendix(names: TypeNames, documented: set) -> list:
    """Every model and enum the page's tables named, until none is left to add."""
    lines = []
    done = set(documented)
    if any(m not in done for m in names.models):
        lines += ["## Models", ""]
    while True:
        pending = [m for m in names.models if m not in done]
        if not pending:
            break
        for model in pending:
            done.add(model)
            lines += model_section(model, names)
    if names.enums:
        lines += ["## Enumerations", ""]
        for enum_name, (_, doc, values) in names.enums.items():
            lines += [f"### {enum_name}", ""]
            if doc:
                lines += [doc, ""]
            lines += [", ".join(f"`{v}`" for v in values), ""]
    return lines


def wire_aliases() -> dict:
    from backend.core.models import audio_wire

    return {audio_wire.AvailabilityReason: "AvailabilityReason", audio_wire.RepeatMode: "RepeatMode"}


