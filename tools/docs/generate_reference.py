def audio_state_page() -> tuple:
    """The page, and every model, enum and alias it documents, for other pages to link."""
    from backend.core.models import audio_wire

    names = TypeNames(aliases=wire_aliases())
    lines = [
        HEADER,
        "# Audio state",
        "",
        "The object `GET /api/audio/state` answers, the `data` of the `source/state` "
        "WebSocket event and the `state` key of `system/initial_state`: one model, "
        "the same on every path. Every field is always present — an absent value is "
        "`null`, never a missing key. Durations and positions are milliseconds; "
        "instants are UTC seconds since the epoch.",
        "",
        "The whole state is **contracted**. " + STABILITY_NOTE,
        "",
        "## AudioState",
        "",
    ]
    lines += field_rows(audio_wire.AudioState, names) + [""]
    variants = typing.get_args(typing.get_args(audio_wire.Details)[0])
    lines += [
        "## Details",
        "",
        "`details` is the selected source's own content, one shape per source, told apart "
        "by `kind`: " + ", ".join(f"[`{v.model_fields['kind'].default}`](#{anchor(v.__name__)})"
                                   for v in variants) + ". It is `null` for the other sources.",
        "",
    ]
    for variant in variants:
        lines += model_section(variant, names)
    documented = {audio_wire.AudioState, *variants}
    lines += appendix(names, documented)
    documented |= set(names.models) | {key for key, _, _ in names.enums.values()}
    return "\n".join(lines).rstrip() + "\n", documented


def render_ws_events(on_audio_state_page: set) -> str:
    from backend.core.models.audio_wire import AudioState

    external = {item: "audio-state.md" for item in on_audio_state_page}
    names = TypeNames(external=external, aliases=wire_aliases())
    contracted = {
        tuple(pair.split("/", 1))
        for pair in api_surface.pinned_events(api_surface.manifests(REPO))
    }
    classes = api_surface.ws_event_classes()

    by_pair: dict = {}
    for cls in classes:
        by_pair.setdefault((cls.CATEGORY, cls.TYPE), []).append(cls)

    lines = [
        HEADER,
        "# WebSocket events",
        "",
        "Every frame on `/ws` is an envelope "
        "`{category, type, origin, data, timestamp}`. `data` is the event's payload, "
        "described below; `origin` is its `source` field when it has one, else the "
        "category; `timestamp` is UTC seconds since the epoch. Besides these events the "
        "server sends `{\"category\": \"system\", \"type\": \"ping\", \"timestamp\": …}` "
        "every 30 seconds, with no `data`.",
        "",
        f"{len(by_pair)} `(category, type)` pairs. " + STABILITY_NOTE,
        "",
    ]
    categories = list(dict.fromkeys(c for c, _ in by_pair))
    lines += ["| Event | Stability |", "|---|---|"]
    for pair in by_pair:
        label = f"{pair[0]}/{pair[1]}"
        lines.append(f"| [`{label}`](#{anchor(label.replace('/', ''))}) | "
                     f"{'contracted' if pair in contracted else 'internal'} |")
    lines.append("")

    for category in categories:
        lines += [f"## {category}", ""]
        for pair, group in by_pair.items():
            if pair[0] != category:
                continue
            label = f"{pair[0]}/{pair[1]}"
            lines += [f"### {label}", ""]
            if pair in contracted:
                lines += ["**Contracted.**", ""]
            for cls in group:
                if len(group) > 1:
                    lines += [f"From `{cls.model_fields['source'].default}`:", ""]
                doc = own_doc(cls)
                if doc:
                    lines += [doc, ""]
                if issubclass(cls, AudioState):
                    lines += ["`data` is the [audio state](audio-state.md).", ""]
                    continue
                if cls.EXCLUDE_NONE:
                    lines += ["A field that is `null` is left out of `data`.", ""]
                lines += (field_rows(cls, names) if cls.model_fields else ["`data` is empty."]) + [""]
    return "\n".join(lines + appendix(names, set())).rstrip() + "\n"


def render_commands() -> str:
    from backend.core.models.session import CommandScope

    app_commands, app_params = api_surface.commands_the_apps_send(REPO)
    if not app_commands:
        raise SystemExit("found no command the apps send in the vendored snapshots")
    names = TypeNames(aliases=wire_aliases())
    scope_text = {
        CommandScope.CONTENT: "starts something new",
        CommandScope.SESSION: "needs a live session",
        CommandScope.RESUME: "works on the session, or on the resume point when none is live",
        CommandScope.DEVICE: "acts on the device, session or not",
    }
    lines = [
        HEADER,
        "# Source commands",
        "",
        "Every command travels on one route, whatever the source:",
        "",
        "```",
        "POST /api/audio/control/{source}",
        '{"command": "<name>", "data": {<parameters>}}',
        "```",
        "",
        "A command the source does not declare, or parameters that do not validate, is "
        "answered `400`, and so is a `session` command sent while nothing plays. The "
        "audio state's `controls` lists the commands a source takes at this moment; "
        "send only those. What the command changed arrives as the next `source/state`.",
        "",
        "The route is **contracted**, and so are the commands the companion apps send "
        "— marked in the tables — and the parameters they pass ("
        + ", ".join(f"`{p}`" for p in sorted(app_params))
        + "), both read from the apps' own sources. A change to one is listed in the "
        "release notes like any contracted change, but no test fails on it yet. Every "
        "other command and parameter is internal. " + STABILITY_NOTE,
        "",
        "When:",
        "",
    ]
    lines += [f"- **{scope.value}** — {text}." for scope, text in scope_text.items()]
    lines.append("")
    for value, cls in api_surface.source_classes():
        lines += [f"## {value}", ""]
        if not cls.COMMANDS:
            lines += ["No commands: the sender controls playback.", ""]
            continue
        lines += ["| Command | When | Parameters | Stability |", "|---|---|---|---|"]
        for command, params in cls.COMMANDS.items():
            scope = cls.COMMAND_SCOPES[command].value
            if params is None:
                rendered = "—"
            else:
                rendered = "<br>".join(
                    f"`{n}`: {cell(names.name(f.annotation))}"
                    + ("" if f.is_required() else " (optional)")
                    for n, f in params.model_fields.items()
                )
            stability = "contracted" if command in app_commands else "internal"
            lines.append(f"| `{command}` | {scope} | {rendered} | {stability} |")
        lines.append("")
    return "\n".join(lines + appendix(names, set())).rstrip() + "\n"


def _response(operation: dict) -> str:
    code, response = api_surface.success_response(operation)
    if code is None:
        return ""
    content = response.get("content", {})
    return api_surface.body(content) if content else f"{code}, no body"


def render_rest(spec: dict) -> str:
    groups: dict = {}
    for path, item in spec["paths"].items():
        segments = path.strip("/").split("/")
        group = "/" + "/".join(segments[:2]) if segments[0] == "api" and len(segments) > 1 else "/" + segments[0]
        for method, operation in item.items():
            if method not in api_surface.HTTP_METHODS:
                continue
            request = api_surface.body(operation.get("requestBody", {}).get("content", {}))
            stability = operation.get("x-stability", "internal")
            groups.setdefault(group, []).append(
                f"| `{method.upper()}` | `{path}` | {request} | {_response(operation)} | {stability} |"
            )
    total = sum(len(rows) for rows in groups.values())
    contracted = sum(row.endswith("| contracted |") for rows in groups.values() for row in rows)
    lines = [
        HEADER,
        "# REST operations",
        "",
        f"The {total} operations of the backend's OpenAPI schema, {contracted} of them "
        "contracted. Each unit serves the full schema at `/api/openapi.json` and an "
        "interactive view at `/api/docs`, where request and response models are described "
        "field by field. Request and response name the schema of the body (`untyped JSON` where "
        "it is untyped).",
        "",
        STABILITY_NOTE,
        "",
    ]
    for group in sorted(groups):
        lines += [f"## {group}", "", "| Method | Path | Request | Response | Stability |",
                  "|---|---|---|---|---|", *groups[group], ""]
    return "\n".join(lines).rstrip() + "\n"


def render_hardware() -> str:
    from backend.hardware import registry

    def code(value) -> str:
        return f"`{value}`" if value else "—"

    lines = [
        HEADER,
        "# Supported hardware",
        "",
        "The audio cards and screens the setup wizard offers. The id is what "
        "`hardware.json` stores; picking a card writes its device-tree overlay to "
        "`/boot/firmware/config.txt`. For wiring, see [Wiring](../hardware/wiring.md).",
        "",
        "## Audio cards",
        "",
        "| Id | Card | Category | Overlay | ALSA card |",
        "|---|---|---|---|---|",
    ]
    for card_id, card in registry.AUDIO_CARDS.items():
        if card_id == "none":
            continue
        lines.append(f"| `{card_id}` | {cell(card['label'])} | {card['category']} | "
                     f"{code(card['overlay'])} | {code(card['card_name'])} |")
    lines += [
        "",
        "`dac` cards need an external amplifier; `amplifier` cards drive speakers directly.",
        "",
        "## Screens",
        "",
        "| Id | Screen | Resolution | Color correction |",
        "|---|---|---|---|",
    ]
    for screen_id, screen in registry.SCREENS.items():
        if screen_id == "none":
            continue
        gains = screen.get("color_correction")
        correction = "R, G, B × " + ", ".join(f"{g:g}" for g in gains) if gains else "—"
        lines.append(f"| `{screen_id}` | {cell(screen['label'])} | {screen['resolution']} | {correction} |")
    lines += [
        "",
        "A color correction is a fixed gain per channel that brings the panel's white to D65; "
        "only a panel calibrated with a colorimeter carries one.",
        "",
        "## Default GPIO pins",
        "",
        "BCM numbering.",
        "",
        "| Input | Pin |",
        "|---|---|",
    ]
    rotary = registry.DEFAULT_ROTARY_PINS
    lines += [
        f"| Rotary encoder CLK | {rotary['clk_pin']} |",
        f"| Rotary encoder DT | {rotary['dt_pin']} |",
        f"| Rotary encoder switch | {rotary['sw_pin']} |",
        f"| IR receiver | {registry.DEFAULT_IR_REMOTE['gpio_pin']} |",
        f"| Power button LED (cathode) | {registry.DEFAULT_POWER_BUTTON['led_gpio_pin']} |",
    ]
    return "\n".join(lines).rstrip() + "\n"


def render_all(spec: dict) -> dict:
    """Every page, by file name under docs/reference/."""
    audio_state, on_audio_state_page = audio_state_page()
    return {
        "audio-state.md": audio_state,
        "ws-events.md": render_ws_events(on_audio_state_page),
        "commands.md": render_commands(),
        "rest.md": render_rest(spec),
        "hardware.md": render_hardware(),
    }


def app_openapi() -> dict:
    from backend.main import app

    return app.openapi()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if a page is stale")
    args = parser.parse_args()

    pages = render_all(app_openapi())
    stale = [name for name, text in pages.items()
             if not (OUT_DIR / name).exists() or (OUT_DIR / name).read_text() != text]
    if args.check:
        for name in stale:
            print(f"stale: docs/reference/{name}")
        return 1 if stale else 0
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name in stale:
        (OUT_DIR / name).write_text(pages[name])
        print(f"wrote docs/reference/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
